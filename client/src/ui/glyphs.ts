// Species silhouettes (D-167): one filled 24 x 24 pictogram per species, so every card shows the
// species itself (a rabbit for rabbits) rather than its family's line drawing. Animals stand in
// side view facing right; plants show their recognisable shape. Built from a few primitives
// (ellipses, polygons, thick segments) that the SVG fills as one shape (nonzero), so the set
// keeps one weight and style. Drawn on the family's tile by FamilyIcon.

/** An ellipse at (cx, cy), radii rx, ry, turned `deg` degrees (clockwise, y down). */
function e(cx: number, cy: number, rx: number, ry: number, deg = 0): string {
  const t = (deg * Math.PI) / 180;
  const [dx, dy] = [Math.cos(t) * rx, Math.sin(t) * rx];
  const f = (v: number) => +v.toFixed(2);
  return (
    `M${f(cx - dx)} ${f(cy - dy)}` +
    `A${rx} ${ry} ${deg} 1 0 ${f(cx + dx)} ${f(cy + dy)}` +
    `A${rx} ${ry} ${deg} 1 0 ${f(cx - dx)} ${f(cy - dy)}Z`
  );
}
/** A circle. */
const c = (cx: number, cy: number, r: number) => e(cx, cy, r, r);
/** A closed polygon through (x, y) pairs. */
function p(...xy: number[]): string {
  let d = `M${xy[0]} ${xy[1]}`;
  for (let i = 2; i < xy.length; i += 2) d += `L${xy[i]} ${xy[i + 1]}`;
  return `${d}Z`;
}
/** A thick segment from (x1, y1) to (x2, y2), `w` wide (a stem, a leg, a stalk). */
function s(x1: number, y1: number, x2: number, y2: number, w: number): string {
  const len = Math.hypot(x2 - x1, y2 - y1) || 1;
  const [nx, ny] = [(-(y2 - y1) / len) * (w / 2), ((x2 - x1) / len) * (w / 2)];
  const f = (v: number) => +v.toFixed(2);
  return p(
    f(x1 + nx),
    f(y1 + ny),
    f(x2 + nx),
    f(y2 + ny),
    f(x2 - nx),
    f(y2 - ny),
    f(x1 - nx),
    f(y1 - ny),
  );
}
/** An upright rectangle. */
const r = (x: number, y: number, w: number, h: number) => p(x, y, x + w, y, x + w, y + h, x, y + h);
/** A chain of thick segments through (x, y) pairs (a cane, a worm, a neck). */
function chain(w: number, ...xy: number[]): string {
  let d = "";
  for (let i = 2; i < xy.length; i += 2) {
    d += s(xy[i - 2] ?? 0, xy[i - 1] ?? 0, xy[i] ?? 0, xy[i + 1] ?? 0, w);
    d += c(xy[i] ?? 0, xy[i + 1] ?? 0, w / 2); // round joints
  }
  return d;
}
/** A grass blade from its base (x, y) to its tip, `w` wide at the base. */
const blade = (x: number, y: number, tx: number, ty: number, w = 1.6) =>
  p(x - w / 2, y, tx, ty, x + w / 2, y);
/** A daisy: a small heart and `n` slim petals radiating from it, gaps between them. */
function daisy(cx: number, cy: number, rad: number, n = 7): string {
  let d = c(cx, cy, rad * 0.24);
  for (let i = 0; i < n; i++) {
    const a = (i * 2 * Math.PI) / n;
    const [x, y] = [cx + Math.cos(a) * rad * 0.6, cy + Math.sin(a) * rad * 0.6];
    d += e(+x.toFixed(2), +y.toFixed(2), rad * 0.36, rad * 0.14, +((a * 180) / Math.PI).toFixed(1));
  }
  return d;
}
/** Leaflets in pairs along a frond from (x1, y1) to (x2, y2). */
function frond(x1: number, y1: number, x2: number, y2: number, n: number, size: number): string {
  let d = s(x1, y1, x2, y2, 0.9);
  const ang = (Math.atan2(y2 - y1, x2 - x1) * 180) / Math.PI;
  for (let i = 1; i <= n; i++) {
    const t = i / (n + 1);
    const [x, y] = [x1 + (x2 - x1) * t, y1 + (y2 - y1) * t];
    const k = size * (1 - 0.55 * t);
    d += e(+x.toFixed(2), +y.toFixed(2), k, k * 0.36, ang + 60);
    d += e(+x.toFixed(2), +y.toFixed(2), k, k * 0.36, ang - 60);
  }
  return d;
}
/** Four upright legs of a quadruped, `w` wide, from the body line `top` to the ground. */
const legs = (top: number, w: number, ...xs: number[]) =>
  xs.map((x) => r(x, top, w, 20.5 - top)).join("");

